#!/bin/sh
# SPDX-License-Identifier: GPL-2.0-only
#
# router-dns-sync -- one idempotent pass that keeps SmartDNS's *upstreams* and
# *local names* in step with what this box actually is.
#
# Why this exists
# ---------------
# smartdns's OpenWrt init emits `resolv-file <dhcp.@dnsmasq[0].resolvfile>` and
# treats every nameserver in that file as an upstream. The stock value is
# /tmp/resolv.conf.d/resolv.conf.auto, which is netifd's own output -- i.e. the
# list of resolvers the *WAN lease* handed us, and /etc/resolv.conf's target.
#
# On this box those two roles collapse into each other as soon as the WAN lease
# (or a stale `network.lan.dns` line, or a DHCP server that answered our own
# DISCOVER) points at 10.1.18.236 -- the router itself. The file then reads
#
#     nameserver 10.1.18.1
#     nameserver 10.1.18.236      <- us
#
# smartdns adds both as upstreams, asks itself, and every query times out while
# the daemon looks perfectly healthy.
#
# So the two roles are split here, once per boot and once per interface event:
#
#   /tmp/resolv.conf                 -> `nameserver 127.0.0.1` (the router uses
#                                       this box's resolver, like a LAN client)
#   /var/etc/router-dns/resolv.upstream
#                                    -> the real upstreams, with loopback and
#                                       every address this box owns filtered
#                                       out; smartdns reads this one
#
# and the router's own name plus the names odhcpd publishes are rendered into
# /var/etc/router-dns/hosts.lan, which smartdns is pointed at with `hosts-file`,
# and into /var/etc/router-dns/hosts.lan.conf as static `address /name/ip` rules,
# which smartdns is pointed at with `conf-file`. (dnsmasq used to be the thing
# that answered `.lan`; it is not a resolver in this firmware, so smartdns has to
# be told about those names explicitly. The address rules are what actually
# answer: smartdns 48.4 caches hosts-file answers with a 120 s TTL and then asks
# upstream instead of re-reading the file.)
#
# Everything is diffed before it is written and smartdns is restarted only when
# something actually changed, so calling this on every ifup is cheap.

DIR=/var/etc/router-dns
UP="$DIR/resolv.upstream"
HOSTS="$DIR/hosts.lan"
# Static `address /name/ip` rules for the same names. smartdns 48.4 turns
# hosts-file entries into *cache* entries with a 120 s TTL and, once that
# expires, asks upstream instead of re-reading the file (measured 2026-10-20:
# OWRT.lan answered for 120 s, then NXDOMAIN forever, while the file, its mtime
# and the smartdns pid were all unchanged). `address` is a rule, not a record:
# it is consulted on every query and never expires, so the local names survive
# whatever the upstream says about `.lan`.
ADDR="$DIR/hosts.lan.conf"

log() { logger -t router-dns "$@"; }

mkdir -p "$DIR" 2>/dev/null || exit 0

# Every IPv4 address this box owns, plus loopback. An "upstream" that is one of
# ours is the bug this file exists for.
own_addrs() {
	{
		printf '%s\n' 127.0.0.1 0.0.0.0
		ip -4 addr show 2>/dev/null |
			awk '$1 == "inet" { sub(/\/.*/, "", $2); print $2 }'
	} | sort -u
}

# Upstreams as netifd currently knows them. ubus is the authoritative source and
# keeps working after /tmp/resolv.conf is no longer netifd's; the resolv.conf
# copies are the fallback for the window before ubus answers (S18).
netifd_dns() {
	local iface
	ubus list network.interface 2>/dev/null |
		sed -n 's/^network\.interface\.\(.*\)$/\1/p' |
		while read -r iface; do
			[ "$iface" = "*" ] && continue
			ubus call "network.interface.$iface" status 2>/dev/null |
				jsonfilter -e '$.data["dns-server"][*]' 2>/dev/null
		done
}

file_dns() {
	local f
	for f in /tmp/resolv.conf.d/resolv.conf.auto /tmp/resolv.conf.auto; do
		[ -f "$f" ] || continue
		awk '$1 == "nameserver" && $2 ~ /^[0-9]+(\.[0-9]+){3}$/ { print $2 }' "$f"
	done
}

# --- upstreams ---------------------------------------------------------------
{
	netifd_dns
	file_dns
} 2>/dev/null | awk 'NF && !seen[$0]++' > "$DIR/.dns.cand"

own="$(own_addrs | tr '\n' ' ')"
want=""
{
	echo "# generated by router-dns-sync -- do not edit"
	echo "# resolvers learned from netifd, with this box's own addresses removed"
	while read -r ns; do
		case " $own " in
		*" $ns "*) continue ;;
		esac
		echo "nameserver $ns"
		want="$want $ns"
	done < "$DIR/.dns.cand"
} > "$DIR/.dns.new"

changed=0
if ! grep -q '^nameserver ' "$DIR/.dns.new" 2>/dev/null &&
	grep -q '^nameserver ' "$UP" 2>/dev/null; then
	# netifd has no resolvers for us at this instant (the WAN is down, or the
	# ifup event arrived before its DNS data did -- measured 2026-10-20: during
	# the boot flap, `ifup` fired while the lease's resolvers were gone). Keep
	# the last known set instead of emptying the resolver: with an empty list
	# smartdns has only the DoT servers left, and on a network that filters 853
	# that is a DNS outage for as long as the link is down.
	rm -f "$DIR/.dns.new"
	want=$(sed -n 's/^nameserver //p' "$UP" | tr '\n' ' ')
	log "no resolvers from netifd right now; keeping the last known set:$(printf ' %s' $want)"
else
	if ! cmp -s "$DIR/.dns.new" "$UP" 2>/dev/null; then
		mv -f "$DIR/.dns.new" "$UP"
		changed=1
	else
		rm -f "$DIR/.dns.new"
	fi
fi

# --- local names -------------------------------------------------------------
lan_ip=$(uci -q get network.lan.ipaddr 2>/dev/null)
lan_ip=${lan_ip%%/*}
host=$(uci -q get system.@system[0].hostname 2>/dev/null)
[ -n "$host" ] || host=$(cat /proc/sys/kernel/hostname 2>/dev/null)

{
	echo "# generated by router-dns-sync -- do not edit"
	if [ -n "$lan_ip" ] && [ -n "$host" ]; then
		# The router's own name. dnsmasq used to publish this; with dnsmasq
		# out of the DNS path nobody else does.
		echo "$lan_ip	$host ${host%.lan}.lan"
	fi
	# Names odhcpd handed out on the LAN. /etc/hosts under one name each, so add
	# the `.lan` form the UI and the acceptance tests use.
	if [ -f /tmp/hosts/odhcpd.hosts.lan ]; then
		while read -r ip name rest; do
			case "$ip" in ''|'#'*) continue ;; esac
			[ -n "$name" ] || continue
			echo "$ip	$name ${name%.lan}.lan"
		done < /tmp/hosts/odhcpd.hosts.lan
	fi
} > "$DIR/.hosts.new"

if ! cmp -s "$DIR/.hosts.new" "$HOSTS" 2>/dev/null; then
	mv -f "$DIR/.hosts.new" "$HOSTS"
	changed=1
else
	rm -f "$DIR/.hosts.new"
fi

# The same names as static `address` rules, in a file smartdns includes with
# `conf-file`. Written from $HOSTS (never from the odhcpd source directly) so
# there is exactly one definition of "the names this box answers for".
{
	echo "# generated by router-dns-sync -- do not edit"
	while read -r ip name rest; do
		case "$ip" in ''|'#'*) continue ;; esac
		case "$ip" in *[!0-9.]*) continue ;; esac
		for n in $name $rest; do
			case "$n" in ''|'#'*) continue ;; esac
			# smartdns rule syntax is /-delimited; refuse anything that
			# could terminate or reshape the rule.
			case "$n" in *[!A-Za-z0-9._-]*) continue ;; esac
			echo "address /$n/$ip"
		done
	done < "$HOSTS"
} > "$DIR/.addr.new"

if ! cmp -s "$DIR/.addr.new" "$ADDR" 2>/dev/null; then
	mv -f "$DIR/.addr.new" "$ADDR"
	changed=1
else
	rm -f "$DIR/.addr.new"
fi

# --- point the router's own resolver at ourselves ----------------------------
# Two paths, because they have different owners:
#
#   /tmp/resolv.conf  netifd rewrites this on every ifup (measured 2026-10-20:
#                     right after `ifup wan` it held the lease's nameservers
#                     again, and on a bad lease that is our own address).
#   /etc/resolv.conf  a base-files symlink to /tmp/resolv.conf. Nothing else
#                     writes it, so an overlay *file* here is what the router's
#                     own getaddrinfo() actually reads, whatever netifd does to
#                     /tmp. sysupgrade -n starts from the symlink again, so both
#                     are re-created on every pass.
RESOLV='nameserver 127.0.0.1
search lan'

if [ -L /tmp/resolv.conf ] || [ "$(cat /tmp/resolv.conf 2>/dev/null)" != "$RESOLV" ]; then
	rm -f /tmp/resolv.conf
	printf '%s\n' "$RESOLV" > /tmp/resolv.conf
fi

if [ -L /etc/resolv.conf ] || [ "$(cat /etc/resolv.conf 2>/dev/null)" != "$RESOLV" ]; then
	rm -f /etc/resolv.conf 2>/dev/null
	if ! printf '%s\n' "$RESOLV" > /etc/resolv.conf 2>/dev/null; then
		log "could not replace /etc/resolv.conf (read-only overlay?); /tmp/resolv.conf still points at us"
	fi
fi

# --- smartdns's view of the world --------------------------------------------
dirty=0

# smartdns's init reads this dnsmasq option to decide what `resolv-file` to
# emit. Pointing it at our filtered copy is the whole reason the loop above is
# safe; dnsmasq itself is not a resolver here (port 0), and if it is ever
# re-enabled it reads a perfectly valid nameserver list.
if [ "$(uci -q get dhcp.@dnsmasq[0].resolvfile)" != "$UP" ]; then
	uci -q set "dhcp.@dnsmasq[0].resolvfile=$UP"
	uci -q commit dhcp
	dirty=1
fi

# smartdns keeps the router's own name and odhcpd's LAN names in a hosts file.
if ! uci -q get smartdns.@smartdns[0].hosts_files 2>/dev/null |
	tr ' ' '\n' | grep -qxF "$HOSTS"; then
	uci -q add_list "smartdns.@smartdns[0].hosts_files=$HOSTS"
	dirty=1
fi

# ...and includes the static address rules from a conf-file. The init renders
# every entry of `conf_files` as `conf-file '<path>'` (only when the file
# exists), so the address rules and the hosts file always describe the same
# set of names.
if ! uci -q get smartdns.@smartdns[0].conf_files 2>/dev/null |
	tr ' ' '\n' | grep -qxF "$ADDR"; then
	uci -q add_list "smartdns.@smartdns[0].conf_files=$ADDR"
	dirty=1
fi

# Upstreams as explicit `config server` sections, one per resolver netifd
# learned -- and none of them one of our own addresses.
#
# Not `resolv-file`: measured 2026-10-20 on smartdns 48.4, a config whose only
# upstreams are nameservers inside the resolv-file resolves nothing (every query
# times out), while `server 10.1.18.6:53` answers immediately. The resolv-file is
# still written and pointed at so that a smartdns which does honour it inherits
# a clean list instead of the loop that started all this.
#
# Sections are *named* (ebpf_up_<ip with dots as underscores>) because
# `@server[N]` renumbers on every delete, and the name doubles as documentation
# in `uci show smartdns`.
have=$(uci -q show smartdns 2>/dev/null |
	sed -n 's/^smartdns\.\(ebpf_up_[0-9_]*\)=server$/\1/p' | sort | tr '\n' ' ')
wantsec=""
for ip in $want; do
	wantsec="$wantsec ebpf_up_$(echo "$ip" | tr . _)"
done
wantsec=$(printf '%s\n' $wantsec | sed '/^$/d' | sort | tr '\n' ' ')

if [ "$have" != "$wantsec" ]; then
	for s in $have; do
		uci -q delete "smartdns.$s"
	done
	for ip in $want; do
		sec="ebpf_up_$(echo "$ip" | tr . _)"
		uci -q set "smartdns.$sec=server"
		uci -q set "smartdns.$sec.enabled=1"
		uci -q set "smartdns.$sec.ip=$ip"
		uci -q set "smartdns.$sec.port=53"
	done
	dirty=1
fi

# Leftovers from the dnsmasq-front design: a `/lan/` upstream pointed at
# 127.0.0.1:6053, the port dnsmasq used to listen on. dnsmasq is not a resolver
# any more, so that upstream is a black hole that makes every `.lan` lookup
# wait for a timeout (measured: `nslookup <host>.lan` -> SERVFAIL).
#
# The same list also held our old hardcoded `223.5.5.5` / `119.29.29.29`
# upstreams. Note that smartdns's init does not read `smartdns.@smartdns[0].server`
# at all (only `config server` sections, which the block above now owns), so
# these entries were inert; they are removed so `uci show smartdns` stops
# implying an upstream that is not used.
for s in $(uci -q get smartdns.@smartdns[0].server 2>/dev/null); do
	case "$s" in
	*/127.0.0.1:6053|127.0.0.1:6053|*/127.0.0.1:6053/*|223.5.5.5|119.29.29.29)
		uci -q del_list "smartdns.@smartdns[0].server=$s"
		dirty=1
		;;
	esac
done

if [ "$dirty" = 1 ]; then
	uci -q commit smartdns
fi

if [ "$changed" = 1 ] || [ "$dirty" = 1 ]; then
	log "upstreams:$(printf ' %s' $want); resolv.conf -> 127.0.0.1; hosts: $HOSTS (+ $ADDR)"
	# Only when it is already running: at S18 smartdns has not started yet and
	# its own init will pick the new config up in a moment.
	if pgrep -f /usr/sbin/smartdns >/dev/null 2>&1; then
		/etc/init.d/smartdns restart >/dev/null 2>&1
	fi
fi

exit 0
